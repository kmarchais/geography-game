import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'

const countries = JSON.parse(readFileSync('public/data/globe/countries.json', 'utf8')).filter((country: { playable: boolean }) => country.playable)
test.describe('French system language', () => {
  test.use({ locale: 'fr-FR' })
  test('translates the game, country prompts, help and controls', async ({ page }) => {
    await page.route('**/atlas-api/runs', route => route.fulfill({ json: { id: '11111111-1111-4111-8111-111111111111', deck: ['TCD', ...countries.map((country: { id: string }) => country.id).filter((id: string) => id !== 'TCD')] } }))
    await page.route('**/atlas-api/runs/*/answers', route => route.fulfill({ json: { complete: false, correct: 0, total: 195, timeMs: 0 } }))
    await page.goto('./')
    await expect(page.locator('html')).toHaveAttribute('lang', 'fr')
    await expect(page).toHaveTitle('Atlas · Défi géographique')
    await expect(page.getByRole('button', { name: 'Jouer', exact: true })).toBeVisible()
    if (page.viewportSize()!.width >= 1000) {await expect(page.getByRole('button', { name: 'Pourquoi 195 pays ?' })).toHaveAttribute('title', "193 États membres de l'ONU + 2 États observateurs.")}
    await expect(page.getByRole('button', { name: 'Zoom avant', exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: 'Jouer', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Tchad', exact: true })).toBeVisible()
    await expect(page.getByTestId('accuracy')).toHaveText('0,0 %')
    await page.getByRole('button', { name: 'Passer', exact: true }).click()
    await expect(page.getByText('Passé : Tchad')).toBeVisible()
    await page.getByRole('button', { name: 'Menu', exact: true }).click()
    await page.getByRole('menuitem', { name: 'Comment jouer' }).click()
    await expect(page.getByRole('heading', { name: 'Retrouvez les 195 pays.' })).toBeVisible()
    await page.getByText('Pourquoi 195 ? Voir la liste des pays', { exact: true }).click()
    await expect(page.locator('.country-list li')).toHaveCount(195)
    await expect(page.locator('.country-list')).toContainText('Allemagne')
    await page.getByRole('button', { name: "Fermer l'aide" }).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
  test('translates the public bug report and validates it in French', async ({ page }) => {
    await page.goto('./')
    await page.getByRole('button', { name: 'Menu', exact: true }).click()
    await page.getByRole('menuitem', { name: 'Signaler un bug' }).click()
    const dialog = page.getByRole('dialog', { name: 'Signaler un bug' })
    await expect(dialog.getByText(/Les signalements sont publics sur GitHub/)).toBeVisible()
    await dialog.getByRole('button', { name: 'Envoyer le signalement', exact: true }).click()
    await expect(dialog.getByText('Ajoutez un titre et décrivez le problème.')).toBeVisible()
    await expect(dialog.getByLabel('Titre', { exact: true })).toBeVisible()
    await expect(dialog.getByLabel("Que s'est-il passé ?", { exact: true })).toBeVisible()
    await dialog.getByRole('button', { name: 'Fermer le signalement' }).click()
    await expect(dialog).toBeHidden()
  })
  test('translates the connected profile and avatar choices', async ({ page }) => {
    await page.route('**/atlas-api/auth/session', route => route.fulfill({ json: { user: { id: '11111111-1111-4111-8111-111111111111', name: 'Alex', avatar: 'preset:earth' }, best: null } }))
    await page.goto('./')
    await page.getByRole('button', { name: 'Menu', exact: true }).click()
    await expect(page.locator('.account-identity strong')).toContainText('Connecté : Alex')
    await page.getByRole('menuitem', { name: 'Modifier le profil', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Votre profil' })
    await expect(dialog.getByRole('button', { name: 'Avatar Boussole', exact: true })).toBeVisible()
    await expect(dialog.getByLabel('Choisir une photo', { exact: true })).toBeAttached()
    await dialog.getByLabel('Pseudo', { exact: true }).fill('')
    await dialog.getByRole('button', { name: 'Enregistrer le profil', exact: true }).click()
    await expect(dialog.getByText('Utilisez un pseudo de 1 à 24 lettres ou chiffres.')).toBeVisible()
    expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await dialog.getByRole('button', { name: 'Fermer le profil' }).click()
  })
})
test.describe('Other system languages', () => {
  test.use({ locale: 'de-DE' })
  test('falls back to English instead of selecting another language', async ({ page }) => {
    await page.goto('./')
    await expect(page.locator('html')).toHaveAttribute('lang', 'en')
    await expect(page.getByRole('button', { name: 'Play', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Play', exact: true })).toBeVisible()
  })
})
